import { beforeEach, expect, it, vi } from 'vitest'
const mock = vi.hoisted(() => ({ user: vi.fn(), staff: vi.fn(), permission: vi.fn(), get: vi.fn(), admit: vi.fn(), verify: vi.fn() }))
vi.mock('@/lib/server/auth/auth', () => ({ getCurrentUser: mock.user, hasStaffRole: mock.staff, hasPermission: mock.permission }))
vi.mock('@/lib/server/settings', () => ({ getSetting: mock.get }))
vi.mock('@/lib/server/tracking/health/tracking-health', () => ({ admitTrackingHealthCheck: mock.admit, verifyTrackingHealth: mock.verify }))
import { POST } from '@/app/api/admin/tracking-health/route'
const request = (origin = 'https://fixture.invalid') => new Request('https://fixture.invalid/api/admin/tracking-health', { method: 'POST', headers: { host: 'fixture.invalid', origin } })
beforeEach(() => {
  vi.resetAllMocks()
  mock.user.mockResolvedValue({ id: 'fixture-admin' }); mock.staff.mockReturnValue(true); mock.permission.mockReturnValue(true); mock.admit.mockReturnValue(true)
  mock.get.mockImplementation(async (key: string) => ({ 'tracking.gtmEnabled': 'true', 'tracking.gtmContainerId': 'GTM-KQ8GR36H', 'tracking.ga4MeasurementId': 'G-ABC1234567' })[key as 'tracking.gtmEnabled'])
  mock.verify.mockResolvedValue({ overall: 'not_verified' })
})
it('requires same-origin admin settings permission before reading settings or contacting Google', async () => {
  expect((await POST(request('https://other.invalid'))).status).toBe(403)
  mock.user.mockResolvedValue(null)
  expect((await POST(request())).status).toBe(401)
  mock.user.mockResolvedValue({ id: 'customer' }); mock.staff.mockReturnValue(false)
  expect((await POST(request())).status).toBe(403)
  mock.staff.mockReturnValue(true); mock.permission.mockReturnValue(false)
  expect((await POST(request())).status).toBe(403)
  expect(mock.get).not.toHaveBeenCalled(); expect(mock.verify).not.toHaveBeenCalled()
})
it('verifies saved settings only and never stores a verification result', async () => {
  const response = await POST(request())
  expect(response.status).toBe(200)
  expect(response.headers.get('cache-control')).toContain('no-store')
  expect(mock.verify).toHaveBeenCalledWith({ enabled: true, containerId: 'GTM-KQ8GR36H', measurementId: 'G-ABC1234567' })
})
it('returns a safe error on settings failures and rate limits before Google calls', async () => {
  mock.admit.mockReturnValue(false)
  const limited = await POST(request())
  expect(limited.status).toBe(429); expect(limited.headers.get('retry-after')).toBe('60')
  expect(mock.verify).not.toHaveBeenCalled()
  mock.admit.mockReturnValue(true); mock.get.mockRejectedValue(Error('database password private-secret'))
  const failed = await POST(request())
  expect(failed.status).toBe(503)
  expect(await failed.text()).not.toContain('private-secret')
})
